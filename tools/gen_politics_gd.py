def sc(no, stem, options, answer, analysis):
    assert len(options) == 4, '单选必须4选项 no=%s' % no
    assert 0 <= answer < 4, '答案越界 no=%s' % no
    return {"no": no, "score": 3, "type": "single",
            "stem": stem, "options": list(options), "answer": answer,
            "analysis": analysis}


def mc(no, stem, options, answer, analysis):
    assert len(options) == 4, '多选必须4选项 no=%s' % no
    assert isinstance(answer, list) and 2 <= len(answer) <= 4, '多选答案2-4项 no=%s' % no
    assert all(0 <= a < 4 for a in answer), '答案越界 no=%s' % no
    return {"no": no, "score": 6, "type": "multiple",
            "stem": stem, "options": list(options), "answer": list(answer),
            "analysis": analysis}


def sub(no, score, stem, answer, analysis):
    return {"no": no, "score": score, "type": "subjective",
            "stem": stem, "answer": answer, "analysis": analysis}


def mod_d1(singles):
    """单项选择题模块：16×3=48"""
