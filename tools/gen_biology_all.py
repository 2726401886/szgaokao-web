def selfcheck():
    print('\n--- selfcheck ---')
    # book / knowledge 结构一致
    for fname, obj in (('biology_book.json', {'books': BOOKS}),
                       ('biology_knowledge.json', {'books': BOOKS})):
        import collections
        nsec = 0
        nq = 0
        np_ = 0
        grades = set()
        for b in obj['books']:
            for c in b['chapters']:
                for s in c['sections']:
                    nsec += 1
                    assert s.get('title') and 'grade' in s, fname + ' 节字段缺失: ' + s['id']
                    grades.add(s['grade'])
                    np_ += len(s.get('points', []))
                    nq += len(s.get('questions', []))
                    assert len(s.get('points', [])) >= 3, fname + ' 知识点不足: ' + s['id']
                    assert len(s.get('questions', [])) >= 6, fname + ' 练习不足: ' + s['id']
                    for q in s['questions']:
                        if q['type'] == 'choice_single':
                            assert len(q['options']) == 4 and 0 <= q['answer'] < 4, q.get('stem', '')[:20]
        print('  %s: %d 册 / %d 节 / %d 知识点 / %d 题 / grades=%s' %
              (fname, len(obj['books']), nsec, np_, nq, sorted(grades)))
        assert nsec >= 16 and nq >= 90, fname + ' 规模不足'
        assert grades <= {7, 8, 9, 10, 11, 12}

    qs = EXAM['questions']
    tc = collections.Counter(q['type'] for q in qs)
    print('  题库：%d 题 %s' % (len(qs), dict(tc)))
    assert len(qs) >= 45, '题库数量不足'
    ids = [q['id'] for q in qs]
    assert len(ids) == len(set(ids)), '题库 id 重复'
    for q in qs:
        if q['type'] == 'choice':
            assert len(q['options']) == 4 and 0 <= q['answer'] < 4
            assert len(set(q['options'])) == 4
        assert q.get('analysis') and q['analysis'].strip()
        if q['type'] == 'read':
            for sq in q['questions']:
                assert sq.get('analysis') and sq['analysis'].strip()
    ch = [q for q in qs if q['type'] == 'choice']
    dist = collections.Counter(q['answer'] for q in ch)
    print('  单选答案分布 A/B/C/D = %s' % [dist.get(i, 0) for i in range(4)])
    assert all(dist.get(i, 0) > 0 for i in range(4))

    us = LINK['units']
    print('  专题包：%d 单元' % len(us))
    assert len(us) == 5, '专题单元数不符'
    for u in us:
        assert u['points'] and u['quiz']
        for p in u['points']:
            assert p.get('h') and p.get('body') and p.get('eg') and p.get('tip')
    print('selfcheck 全部通过')


