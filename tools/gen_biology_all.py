def pt(t, e):
    return {'t': t, 'e': e}


def cs(stem, options, answer, analysis, kaodian=''):
    assert len(options) == 4 and 0 <= answer < 4, 'choice_single 选项/答案异常: ' + stem[:20]
    assert len(set(options)) == 4, '选项重复: ' + stem[:20]
    return {'type': 'choice_single', 'stem': stem, 'options': list(options),
            'answer': answer, 'analysis': analysis, 'kaodian': kaodian}


def fl(stem, answer, analysis, kaodian=''):
    return {'type': 'fill', 'stem': stem, 'answer': answer,
            'analysis': analysis, 'kaodian': kaodian}


def sh(stem, answer, analysis, kaodian=''):
    return {'type': 'short', 'stem': stem, 'answer': answer,
            'analysis': analysis, 'kaodian': kaodian}


def ex(stem, sub, answer, analysis, kaodian=''):
    return {'type': 'experiment', 'stem': stem, 'sub': list(sub) if sub else None,
            'answer': answer, 'analysis': analysis, 'kaodian': kaodian}


def section(sec_id, title, grade, points, questions):
    for p in points:
        assert p.get('t') and p.get('e'), sec_id + ' 知识点字段缺失'
    for q in questions:
        assert q.get('stem') and q.get('analysis'), sec_id + ' 题目/解析缺失'
        if q['type'] == 'choice_single':
            assert 0 <= q['answer'] < len(q['options']), sec_id + ' 单选答案越界'
            assert len(q['options']) == 4, sec_id + ' 单选须 4 选项'
        else:
            assert q.get('answer') and q['answer'].strip(), sec_id + ' 非选择答案缺失'
    return {'id': sec_id, 'title': title, 'grade': grade,
            'points': points, 'questions': questions}


def chapter(ch_id, title, sections):
    return {'id': ch_id, 'title': title, 'sections': sections}


def book(bid, name, term, chapters):
    return {'id': bid, 'name': name, 'term': term, 'chapters': chapters}


