def balance_answers(questions):
    idx = 0
    for q in questions:
        if q['type'] != 'choice':
            continue
        desired = idx % 4
        idx += 1
        opts = q['options']
        correct = opts[q['answer']]
        shift = (q['answer'] - desired) % len(opts)
        new = opts[shift:] + opts[:shift]
        assert new[desired] == correct
        q['options'] = new
        q['answer'] = desired
    return questions


