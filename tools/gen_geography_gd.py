def selfcheck():
    issues = []
    # 白名单：真题图表的规范代号/单位，属真题原文不可删改
    # LT/LI=长波/大气逆辐射，MJ=单位，km=千米，ii/iii=阶段代号，Kt/J3p 等=地层代号
    WHITE = set('lt li mj km p ii iii kt j3p j3s j2p js jp kg'.split())

    def scan(field, t):
        if not isinstance(t, str):
            return
        import re as _re
        for w in _re.findall(r'[A-Za-z]{2,}', t):
            if w.lower() in WHITE:
                continue
            issues.append(('embedded-en', '%s :: %s' % (field, w)))

    p = PAPER
    assert p['kind'] == 'real-paper', p['id']
    assert p['totalScore'] == 100, p['id']
    n_mc = n_sub = 0
    seen = set()
    for m in p['modules']:
        for part in m['parts']:
            for q in part['questions']:
                for k in ('no', 'score', 'type', 'stem', 'answer', 'analysis'):
                    assert k in q, '缺字段 %s' % k
                assert q['no'] not in seen, '题号重复 %s' % q['no']
                seen.add(q['no'])
                scan('stem', q['stem'])
                scan('analysis', q['analysis'])
                scan('answer', q['answer'])
                if q.get('figure'):
                    scan('figure', q['figure'])
                if q['type'] == 'single':
                    n_mc += 1
                    assert len(q['options']) == 4 and 0 <= q['answer'] < 4
                    assert len(set(q['options'])) == 4, '选项重复 no=%s' % q['no']
                    for o in q['options']:
                        scan('opt', o)
                elif q['type'] == 'subjective':
                    n_sub += 1
    assert n_mc == 16, '选择题数=%d' % n_mc
    assert n_sub == 3, '非选择题数=%d' % n_sub
    total = sum(q['score'] for m in p['modules'] for pt in m['parts'] for q in pt['questions'])
    assert total == 100, '总分=%d' % total
    if issues:
        from collections import Counter
        print('体检问题:', Counter(k for k, _ in issues))
        for k, v in issues[:20]:
            print(' [%s] %s' % (k, v))
        raise SystemExit('内容体检未通过')
    print('[selfcheck] 通过：2024 真题 1 套 / 选择题%d + 非选择题%d = %d题 / 总分%d'
          % (n_mc, n_sub, n_mc + n_sub, total))


