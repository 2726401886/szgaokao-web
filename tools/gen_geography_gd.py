def build_modules(choice, required, optional=None):
    parts = [{"id": "c", "name": "一、选择题（共16小题，每小题3分，共48分）", "score": 48,
              "questions": list(choice)}]
    mods = [{"id": "d1", "name": "一、选择题", "score": 48,
             "note": "本大题共 16 小题，每小题 3 分，共 48 分。每小题四个选项，只有一项符合题目要求。",
             "parts": parts}]
    req_score = sum(q["score"] for q in required)
    req_parts = [{"id": "r", "name": "二、非选择题（必考题）", "score": req_score, "questions": list(required)}]
    mods.append({"id": "d2", "name": "二、非选择题（必考）", "score": req_score,
                 "note": "本大题为必考题，共 %d 分。根据要求作答。" % req_score, "parts": req_parts})
    if optional:
        # 二选一选考题：两题任选其一作答，卷面计 10 分（非两题相加）
        opt_parts = [{"id": "o", "name": "三、选考题（二选一，任选 1 题，10 分）", "score": 10,
                      "questions": list(optional)}]
        mods.append({"id": "d3", "name": "三、选考题（二选一）", "score": 10,
                     "note": "本题为选考题，从 19、20 两题中任选一题作答，10 分。", "parts": opt_parts})
    return mods


