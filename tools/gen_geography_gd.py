def selfcheck():
    import re as _re
    from collections import Counter
    # 白名单：真题图表的规范代号 / 单位 / 技术术语，属真题原文或学科本质，不可删改
    WHITE = set('lt li mj km p ii iii kt j3p j3s j2p js jp kg gis rs gps bds jit co acd'.split())
    issues = []
    for p in PAPERS:
        assert p["kind"] == "real-paper", p["id"]
        assert p["totalScore"] == 100, p["id"]
        seen = set()
        n_mc = n_sub = 0
        n_fig = 0
        for m in p["modules"]:
            for pt in m["parts"]:
                for q in pt["questions"]:
                    for k in ("no", "score", "type", "stem", "answer", "analysis"):
                        assert k in q, "%s 缺字段 %s" % (p["id"], k)
                    assert q["no"] not in seen, "%s 题号重复 %s" % (p["id"], q["no"])
                    seen.add(q["no"])
                    for fld in ("stem", "analysis", "answer"):
                        t = q[fld]
                        if not isinstance(t, str):
                            continue
                        for w in _re.findall(r'[A-Za-z]{2,}', t):
                            if w.lower() in WHITE:
                                continue
                            issues.append(('%s:%s' % (p["id"], fld), w))
                    if q.get("figure"):
                        n_fig += 1
                        for w in _re.findall(r'[A-Za-z]{2,}', q["figure"]):
                            if w.lower() in WHITE:
                                continue
                            issues.append(('%s:figure' % p["id"], w))
                    if q["type"] == "single":
                        n_mc += 1
                        assert len(q["options"]) == 4 and 0 <= q["answer"] < 4, "%s no=%s" % (p["id"], q["no"])
                        assert len(set(q["options"])) == 4, "选项重复 %s no=%s" % (p["id"], q["no"])
                        for o in q["options"]:
                            for w in _re.findall(r'[A-Za-z]{2,}', o):
                                if w.lower() in WHITE:
                                    continue
                                issues.append(('%s:opt' % p["id"], w))
                    elif q["type"] == "subjective":
                        n_sub += 1
        total = sum(m["score"] for m in p["modules"])
        assert n_mc == 16, "%s 选择题数=%d" % (p["id"], n_mc)
        assert total == 100, "%s 总分=%d" % (p["id"], total)
        assert n_fig >= 2, "%s 图表文字化说明不足（图表题=%d）" % (p["id"], n_fig)
        maxno = max(seen)
        assert seen == set(range(1, maxno + 1)), "%s 题号不连续: %s" % (p["id"], sorted(seen))
        print("  [selfcheck] %s 通过：选择%d + 非选择%d = %d题 / 模块总分%d / 图表题%d"
              % (p["id"], n_mc, n_sub, len(seen), total, n_fig))
    if issues:
        print("体检问题:", Counter(k for k, _ in issues))
        for k, v in issues[:20]:
            print(" [%s] %s" % (k, v))
        raise SystemExit("内容体检未通过")
    print("[selfcheck] 全部通过：共 %d 套卷（%s）" % (len(PAPERS), ",".join(str(p["year"]) for p in PAPERS)))


