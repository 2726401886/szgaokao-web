# ---------- 组装 ----------
CONTENT = {7: G7, 8: G8, 9: G9, 10: G10, 11: G11, 12: G12}
NEW_TOPICS = {'质量与密度(八)'}

def main():
    import re as _re
    d = json.load(open(DATA, encoding='utf-8'))
    # 仅保留原始 ph* 题库（50 题），丢弃任何先前生成的 p<grade>* 条目，保证从干净基线重建
    qs = [q for q in d['questions'] if _re.match(r'^ph[a-z]', q['id'])]
    from collections import defaultdict
    cnt = defaultdict(lambda: defaultdict(int))
    for q in qs:
        cnt[q['grade']][q['type']] += 1
    used_ids = {q['id'] for q in qs}

    added = 0
    for grade in sorted(CONTENT):
        block = CONTENT[grade]
        for t in ['choice', 'fill', 'read', 'write']:
            need = max(0, QUOTA[t] - cnt[grade][t])
            pool = block[t][:need]
            # 若内容不足则尽量补充（不足也能跑，只是配额未满）
            n = 0
            for item in pool:
                n += 1
                # 生成唯一 id
                base = 'p%d%s' % (grade, TI[t])
                i = 1
                while ('%s%03d' % (base, i)) in used_ids:
                    i += 1
                qid = '%s%03d' % (base, i)
                used_ids.add(qid)
                q = {'id': qid, 'grade': grade, 'type': t}
                q.update(item)
                qs.append(q)
                added += 1
            if n < need:
                print('  注意: grade %d %s 内容不足，仅补 %d/%d' % (grade, t, n, need))

    # topics 去重并按现有顺序补充新主题
    topics = list(d.get('topics', []))
    for tp in NEW_TOPICS:
        if tp not in topics:
            topics.append(tp)
    d['questions'] = qs
    d['topics'] = topics
    json.dump(d, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    # 统计
    from collections import Counter
    gc = defaultdict(Counter)
    for q in qs:
        gc[q['grade']][q['type']] += 1
    print('total', len(qs), 'added', added)
    for g in sorted(gc):
        print('grade', g, dict(gc[g]))

    # ---------- 同步 worker 内嵌 physics_exam_default ----------
    obj = {'questions': qs, 'topics': topics}
    inline = 'var physics_exam_default = ' + json.dumps(obj, ensure_ascii=False, separators=(',', ':')) + ';'
    s = open(WORKER, encoding='utf-8').read()
    start = s.index('var physics_exam_default = ')
    end = s.index('\n', start)
    s = s[:start] + inline + s[end:]
    open(WORKER, 'w', encoding='utf-8').write(s)
    print('worker inline updated, length', len(inline))

if __name__ == '__main__':
    main()
