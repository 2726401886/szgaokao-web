def selfcheck(data):
    issues = []
    total_q = 0
    for b in data['books']:
        for c in b['chapters']:
            for s in c['sections']:
                qs = s.get('questions', [])
                if len(qs) < 10:
                    issues.append('题目不足10: %s %s (%d)' % (c['title'], s['title'], len(qs)))
                for i, q in enumerate(qs):
                    t = q.get('type')
                    if t in ('choice_single', 'choice_multi'):
                        opts = q.get('options', [])
                        if len(opts) < 2:
                            issues.append('%s %s 选项过少' % (s['title'], i))
                        ans = q.get('answer')
                        if t == 'choice_single':
                            if not isinstance(ans, int) or ans < 0 or ans >= len(opts):
                                issues.append('%s %s 单选答案越界' % (s['title'], i))
                        else:
                            if not (isinstance(ans, list) and all(0 <= a < len(opts) for a in ans)):
                                issues.append('%s %s 多选答案非法' % (s['title'], i))
                    if not q.get('analysis'):
                        issues.append('%s %s 缺详解' % (s['title'], i))
                    # 禁英文夹串：仅标记长度≥3且非单位/符号的英文字母串（公式/单位多为≤2字母或已在白名单）
                    txt = (q.get('stem','') + ' ' + q.get('answer','') if isinstance(q.get('answer'),str) else q.get('stem',''))
                    for tok in re.findall(r'[A-Za-z]{3,}', txt):
                        if tok.lower() not in UNIT_OK:
                            issues.append('%s %s 含英文夹串:%s' % (s['title'], i, tok))
                            break
                    total_q += 1
                if not s.get('points'):
                    issues.append('%s %s 缺考点讲解' % (c['title'], s['title']))
    return issues, total_q

