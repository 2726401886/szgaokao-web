# ---------- 工具：构造题目 ----------
def ch(q, options, answer, analysis, kd=''):
    return {'type': 'choice_single', 'stem': q, 'options': options, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

def cm(q, options, answer, analysis, kd=''):
    return {'type': 'choice_multi', 'stem': q, 'options': options, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

def fl(stem, answer, analysis, kd=''):
    return {'type': 'fill', 'stem': stem, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

def dr(stem, answer, analysis, kd=''):
    return {'type': 'drawing', 'stem': stem, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

def ex(stem, sub, analysis, kd=''):
    return {'type': 'experiment', 'stem': stem, 'sub': sub, 'analysis': analysis, 'kaodian': kd}

def ca(stem, answer, analysis, kd=''):
    return {'type': 'calculation', 'stem': stem, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

def sh(stem, answer, analysis, kd=''):
    return {'type': 'short', 'stem': stem, 'answer': answer, 'analysis': analysis, 'kaodian': kd}

# 计算模板：用 lambda 计算，避免手写答案出错
def calc_from_template(tpl):
    """tpl: dict{stem_fmt, inputs:[(name,lo,hi,step)], expr:lambda **kw -> 数值, unit, kind}
    kind: 'fill' | 'choice' | 'calc'，自动生成正确选项/答案。"""
    ins = [(n, lo, hi, st) for (n, lo, hi, st) in tpl['inputs']]
    vals = {}
    for (n, lo, hi, st) in ins:
        try:
            st_v = float(st)
        except (TypeError, ValueError):
            st_v = 0.0
        lo_f, hi_f = float(lo), float(hi)
        if st_v == 0 or abs(st_v - round(st_v)) > 1e-9:
            # 连续随机（无步长或分数步长）
            vals[n] = lo_f + random.random() * (hi_f - lo_f)
        else:
            lo_i, hi_i, st_i = int(round(lo_f)), int(round(hi_f)), int(round(st_v))
            if (hi_i - lo_i) < st_i:
                vals[n] = lo_i
            else:
                vals[n] = random.choice(range(lo_i, hi_i + 1, st_i))
    # 约束守卫：确保生成的参数满足模板要求（如 v2>v1），最多重试 25 次
    guard = tpl.get('guard')
    tries = 0
    while callable(guard) and tries < 25:
        try:
            if guard(**vals):
                break
        except Exception:
            pass
        # 重新抽取参数
        for (n, lo, hi, st) in ins:
            try:
                st_v = float(st)
            except (TypeError, ValueError):
                st_v = 0.0
            lo_f, hi_f = float(lo), float(hi)
            if st_v == 0 or abs(st_v - round(st_v)) > 1e-9:
                vals[n] = lo_f + random.random() * (hi_f - lo_f)
            else:
                lo_i, hi_i, st_i = int(round(lo_f)), int(round(hi_f)), int(round(st_v))
                if (hi_i - lo_i) < st_i:
                    vals[n] = lo_i
                else:
                    vals[n] = random.choice(range(lo_i, hi_i + 1, st_i))
        tries += 1
    ans = tpl['expr'](**vals)
    # 取整/保留
    if isinstance(ans, float):
        ans = round(ans, 3)
    kd = tpl.get('kaodian', '')
    # 派生量（如 V = v2 - v1），供 analysis_fmt 使用
    der = {}
    if 'derived' in tpl and callable(tpl['derived']):
        try:
            der = tpl['derived'](**vals) or {}
        except Exception:
            der = {}
    fkw = dict(vals); fkw['ans'] = ans; fkw.update(der)
    if tpl['kind'] == 'fill':
        return fl(tpl['stem_fmt'].format(**vals), str(ans) + (tpl.get('unit', '')), tpl.get('analysis_fmt', '').format(**fkw), kd)
    if tpl['kind'] == 'calc':
        an = tpl.get('analysis_fmt', '根据公式得 {ans} ' + tpl.get('unit', '')).format(**fkw)
        return ca(tpl['stem_fmt'].format(**vals), str(ans) + (tpl.get('unit', '')), an, kd)
    # choice：正确项 + 3 个扰动错误项
    opts = [str(ans) + tpl.get('unit', '')]
    base_wrong = [ans * 1.5, ans * 0.5, ans + (vals.get('v', 1) or 1), ans - (vals.get('v', 1) or 1)]
    for w in base_wrong:
        if isinstance(w, float):
            w = round(w, 3)
        s = str(w) + tpl.get('unit', '')
        if s not in opts:
            opts.append(s)
    opts = opts[:4]
    while len(opts) < 4:
        opts.append(str(round(ans + len(opts), 3)) + tpl.get('unit', ''))
    random.shuffle(opts)
    correct = opts.index(str(ans) + tpl.get('unit', ''))
    return ch(tpl['stem_fmt'].format(**vals), opts, correct, tpl.get('analysis_fmt', '由公式计算得 {ans}。').format(**fkw), kd)

def build_section(sec):
    out = {'id': sec['id'], 'title': sec['title'], 'grade': sec['grade'], 'points': [], 'questions': []}
    for p in sec['points']:
        out['points'].append({'t': p['t'], 'e': p['e']})
        out['questions'].append(ch(p['kq']['q'], p['kq']['options'], p['kq']['answer'], p['kq']['analysis'], p['t']))
    for q in sec.get('qs', []):
        out['questions'].append(q)
    for tpl in sec.get('calc', []):
        if isinstance(tpl, dict) and 'type' in tpl:
            out['questions'].append(tpl)
            continue
        n = tpl.get('n', 3)
        for _ in range(n):
            out['questions'].append(calc_from_template(tpl))
    # 兜底：不足 10 题时，复用本节的 calc 模板（换随机参数）补齐，保证 ≥10 且切题
    calcs = sec.get('calc', [])
    idx = 0
    while len(out['questions']) < 10 and calcs:
        t = calcs[idx % len(calcs)]
        if isinstance(t, dict) and 'type' in t:
            out['questions'].append(t)
        else:
            out['questions'].append(calc_from_template(t))
        idx += 1
    # 兜底2：纯概念节（无 calc 模板）仍不足 10 题时，用本节“考点讲解”生成简答题/填空题补齐
    if len(out['questions']) < 10 and not calcs:
        pts = sec.get('points', [])
        i = 0
        while len(out['questions']) < 10 and pts:
            p = pts[i % len(pts)]
            if i % 2 == 0:
                out['questions'].append(
                    sh('请简述“%s”的主要内容。' % p['t'], p['e'], '考点自测。', p['t']))
            else:
                out['questions'].append(
                    fl('（考点自测）“%s”是指____。' % p['t'], p['t'], '考点自测。', p['t']))
            i += 1
        while len(out['questions']) < 10:
            out['questions'].append(
                sh('请结合本节内容，说明“%s”的核心思想。' % sec.get('title', '本节'),
                   '详见本节考点讲解。', '考点自测。', sec.get('title', '本节')))
    return out

def build_chapter(ch):
    return {'id': ch['id'], 'title': ch['title'],
            'sections': [build_section(s) for s in ch['sections']]}

def build_book(book):
    return {'id': book['id'], 'name': book['name'], 'term': book['term'],
            'chapters': [build_chapter(c) for c in book['chapters']]}

