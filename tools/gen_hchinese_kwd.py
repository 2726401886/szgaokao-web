def CH(no, stem, opts, ans, analysis=''):
    ai = LET.index(ans.upper())
    assert 0 <= ai < len(opts), (no, ans, len(opts))
    assert len(opts) == 4, (no, 'need 4 options', len(opts))
    return {'no': no, 'type': 'choice', 'stem': stem, 'options': list(opts), 'answer': ai, 'analysis': analysis}


def SH(no, stem, answer, analysis=''):
    return {'no': no, 'type': 'subjective', 'stem': stem, 'answer': answer, 'analysis': analysis}


def sec(name, score, questions):
    return {'name': name, 'score': score, 'questions': questions}


def unit(uid, no, title, desc, sections):
    n = sum(len(s['questions']) for s in sections)
    return {'id': uid, 'no': no, 'title': title, 'desc': desc, 'questionCount': n, 'sections': sections}


