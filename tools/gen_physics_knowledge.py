# —— 生成逻辑：按节确定性挑选 >=12 题（题型覆盖中高考），选项打乱 ——
TYPES = ['choice_single','choice_multi','fill','calculation','short','experiment']
QUOTA = [('choice_single',5),('choice_multi',2),('fill',2),('calculation',1),('short',1),('experiment',1)]  # 共 12

def shuffle_opts(q, rng):
    if q['type'] in ('choice_single','choice_multi'):
        opts = q['options'][:]
        rng.shuffle(opts)
        ans = q['answer']
        if isinstance(ans, int):
            new_ans = opts.index(q['options'][ans])
        else:
            new_ans = [opts.index(q['options'][a]) for a in ans]
        q2 = dict(q); q2['options'] = opts; q2['answer'] = new_ans
        return q2
    return dict(q)

def pick_questions(pool, rng, n=12):
    by_type = {t: [q for q in pool if q['type']==t] for t in TYPES}
    chosen = []
    for t, cnt in QUOTA:
        avail = by_type.get(t, [])
        for _ in range(min(cnt, len(avail))):
            chosen.append(avail.pop(0) if False else rng.choice(avail))
            # 避免同一题目重复：用已选集合
    # 去重（按 stem）
    seen = set(); uniq = []
    for q in chosen:
        if q['stem'] not in seen:
            seen.add(q['stem']); uniq.append(q)
    # 补足到 n 题（从剩余池随机）
    rest = [q for q in pool if q['stem'] not in seen]
    rng.shuffle(rest)
    while len(uniq) < n and rest:
        uniq.append(rest.pop())
    # 打乱顺序并打乱选项
    rng.shuffle(uniq)
    return [shuffle_opts(q, rng) for q in uniq[:n]]

def build():
    out = {'edition': EDITION, 'books': []}
    for b in BOOK['books']:
        nb = {'id': b['id'], 'name': b['name'], 'term': b['term'], 'chapters': []}
        for c in b['chapters']:
            base = CH.get(c['id'])
            nc = {'id': c['id'], 'title': c['title'], 'sections': []}
            for s in c['sections']:
                rng = random.Random(hash(('kn', s['id'])))
                if base:
                    points = (base['points'][:3] if len(base['points'])>=3 else base['points'])
                    qs = pick_questions(base['qs'], rng, 12)
                else:
                    # fallback：复用课本同步内容，保证完整性
                    points = s.get('points', [])[:3]
                    qs = s.get('questions', [])[:12]
                nc['sections'].append({'id': s['id'], 'title': s['title'], 'grade': s['grade'], 'points': points, 'questions': qs})
            nb['chapters'].append(nc)
        out['books'].append(nb)
    return out

