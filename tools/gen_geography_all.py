def balance_answers(questions):
    """全局轮转摆位，保证 A/B/C/D 均匀（仅对 choice 生效）"""
    idx = 0
    for q in questions:
        if q['type'] != 'choice':
            continue
        desired = idx % 4
        idx += 1
        opts = q['options']
        correct = opts[q['answer']]
        shift = (q['answer'] - desired) % len(opts)
        new = opts[shift:] + opts[:shift]
        assert new[desired] == correct, '答案摆位校验失败'
        q['options'] = new
        q['answer'] = desired
    return questions


