def balance_answers(qs):
    """把选择题正确答案确定性地轮转到 A/B/C/D，使分布均衡、可复现。
    含“以上”兜底选项的题目跳过（该类选项必须固定在末位）。"""
    idx = 0
    for q in qs:
        if q['type'] != 'choice':
            continue
        opts = q['options']
        if any(('以上' in o) or ('都对' in o) or ('都不对' in o) or ('都可以' in o) for o in opts):
            continue
        target = idx % 4
        idx += 1
        cur = q['answer']
        if cur != target:
            opts[cur], opts[target] = opts[target], opts[cur]
            q['answer'] = target
    return qs


