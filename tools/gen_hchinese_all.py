def balance_answers(questions):
    idx = 0
    for q in questions:
        if q["type"] != "choice":
            continue
        desired = idx % 4
        idx += 1
        opts = q["options"]
        correct = opts[q["answer"]]
        n = len(opts)
        shift = (q["answer"] - desired) % n
        new_opts = opts[shift:] + opts[:shift]
        assert new_opts[desired] == correct, "balance failed: %s" % q["id"]
        q["options"] = new_opts
        q["answer"] = desired
    return questions

