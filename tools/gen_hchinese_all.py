def assign_grades(questions):
    """按难度分配年级：难度1→高一(10)、2→高二(11)、3→高三(12)，
    同难度内轮转避免单一年级过于集中。页面筛选用 10/11/12。"""
    buckets = {1: [], 2: [], 3: []}
    for q in questions:
        if q["grade"] is None:
            buckets[q["difficulty"]].append(q)
    for diff, qs in buckets.items():
        if not qs:
            continue
        want = {1: 10, 2: 11, 3: 12}[diff]
        # 难度3 若过多，均匀溢出到 10/11/12
        for i, q in enumerate(qs):
            g = want if len(qs) <= max(1, len(questions) // 8) else [10, 11, 12][i % 3]
            q["grade"] = g
    return questions

