def selfcheck():
    issues = []
    WHITE = set('abc abcde'.split())  # 内容字符串里允许出现的英文词白名单（教学内容的英文缩写等，当前为空）

    def check_str(field, t):
        if not isinstance(t, str):
            return
        for w in re.findall(r'[A-Za-z]{3,}', t):
            if w.lower() in WHITE:
                continue
            # 全英文纯字母串（非中文夹带）也记一笔，便于人工复核
            issues.append(('embedded-en', '%s :: %s' % (field, w)))

    # a) 扫描全部用户可见内容字符串，揪出夹带的英文单词
    for g in KNOWLEDGE['sections']['knowledge']['groups']:
        check_str('group.title', g.get('title', ''))
        check_str('group.grade_tag', g.get('grade_tag', ''))
        for it in g['items']:
            check_str('term', it['term'])
            check_str('jieshi', it['jieshi'])
            kao = it['kao']
            check_str('kao.q', kao['q'])
            for o in kao['options']:
                check_str('kao.opt', o)
    for q in EXAM_QUESTIONS:
        check_str('exam.topic', q['topic'])
        if q['type'] == 'read':
            check_str('exam.title', q.get('title', ''))
            check_str('exam.passage', q.get('passage', ''))
            for s in q['questions']:
                check_str('exam.rstem', s['stem'])
                for o in s['options']:
                    check_str('exam.ropt', o)
                check_str('exam.ranalysis', s['analysis'])
            continue
        check_str('exam.stem', q['stem'])
        for o in q.get('options', []):
            check_str('exam.opt', o)
        check_str('exam.analysis', q['analysis'])
        if q['type'] in ('fill', 'write'):
            check_str('exam.answer', q['answer'])
    for u in LINK['units']:
        check_str('link.title', u['title'])
        check_str('link.grade_tag', u.get('grade_tag', ''))
        check_str('link.summary', u['summary'])
        for p in u['points']:
            check_str('point.h', p['h'])
            check_str('point.body', p['body'])
            check_str('point.eg', p.get('eg', ''))
            check_str('point.tip', p.get('tip', ''))
        for q in u['quiz']:
            check_str('link.qstem', q['stem'])
            for o in q['options']:
                check_str('link.qopt', o)
            check_str('link.qanalysis', q['analysis'])
    # b) grade 取值必须 ∈ {7,8,9,10,11,12}
    all_grades = set(q['grade'] for q in EXAM_QUESTIONS)
    assert all_grades <= set((7, 8, 9, 10, 11, 12)), 'EXAM grade 取值错误: %r' % all_grades
    # c) 答案越界（choice/fill/read 小题）
    for q in EXAM_QUESTIONS:
        if q['type'] == 'choice':
            assert 0 <= q['answer'] < len(q['options']), 'choice 答案越界 ' + q['id']
        elif q['type'] == 'read':
            for s in q['questions']:
                assert 0 <= s['answer'] < len(s['options']), 'read 小题越界 ' + q['id']
    # d) 题目 id 唯一
    ids = [q['id'] for q in EXAM_QUESTIONS]
    assert len(ids) == len(set(ids)), 'EXAM 题目 id 重复'
    # e) 知识点 id 唯一
    kid = [it['id'] for g in KNOWLEDGE['sections']['knowledge']['groups'] for it in g['items']]
    assert len(kid) == len(set(kid)), '知识点 id 重复'
    # f) 单元 / 单元小测 id 唯一
    uid = [u['id'] for u in LINK['units']]
    assert len(uid) == len(set(uid)), '单元 id 重复'
    for u in LINK['units']:
        for q in u['quiz']:
            assert 0 <= q['answer'] < len(q['options']), 'link 小测越界 ' + q['id']
    if issues:
        from collections import Counter
        print('体检问题:', Counter(k for k, _ in issues))
        for k, v in issues[:20]:
            print(' [%s] %s' % (k, v))
        raise SystemExit('内容体检未通过')
    print('[selfcheck] 通过：EXAM %d 题 / 知识点 %d / 单元 %d' % (len(EXAM_QUESTIONS), len(kid), len(LINK['units'])))


