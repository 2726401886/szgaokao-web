# 题目构造助手
# ============================================================
_exam_seq = {'choice': 0, 'fill': 0, 'read': 0, 'write': 0}


def qc(grade, topic, difficulty, stem, options, answer, analysis):
    _exam_seq['choice'] += 1
    assert len(options) == 4, '选项必须为 4 个: ' + stem[:20]
    assert 0 <= answer < len(options), 'answer 越界'
    assert len(set(options)) == 4, '选项重复: ' + stem[:20]
    return {'id': 'hsc%03d' % _exam_seq['choice'], 'grade': grade, 'topic': topic,
            'type': 'choice', 'difficulty': difficulty, 'stem': stem,
            'options': list(options), 'answer': answer, 'analysis': analysis}


def qf(grade, topic, difficulty, stem, answer, analysis):
    _exam_seq['fill'] += 1
    return {'id': 'hsf%03d' % _exam_seq['fill'], 'grade': grade, 'topic': topic,
            'type': 'fill', 'difficulty': difficulty, 'stem': stem,
            'answer': answer, 'analysis': analysis}


def qr(grade, topic, difficulty, title, passage, subs):
    _exam_seq['read'] += 1
    assert subs and all(0 <= s['answer'] < len(s['options']) for s in subs), 'read 小题答案越界'
    return {'id': 'hsr%03d' % _exam_seq['read'], 'grade': grade, 'topic': topic,
            'type': 'read', 'difficulty': difficulty, 'title': title,
            'passage': passage, 'questions': subs}


def lq(grade, topic, difficulty, stem, answer, analysis):
    _exam_seq['write'] += 1
    return {'id': 'hsw%03d' % _exam_seq['write'], 'grade': grade, 'topic': topic,
            'type': 'write', 'difficulty': difficulty, 'stem': stem,
            'answer': answer, 'analysis': analysis}


def kp(id, term, jieshi, kao):
    assert 0 <= kao['answer'] < len(kao['options']), 'kao 答案越界: ' + id
    return {'id': id, 'term': term, 'jieshi': jieshi, 'kao': kao}


def sub(stem, options, answer, analysis):
    return {'stem': stem, 'options': list(options), 'answer': answer, 'analysis': analysis}


