def lp(id, points, quiz):
    assert all(0 <= q['answer'] < len(q['options']) for q in quiz), id + ' quiz 答案越界'
    return {'id': id, 'points': points, 'quiz': quiz}


def pt(h, body, eg, tip):
    return {'h': h, 'body': body, 'eg': eg, 'tip': tip}


def lq2(id, stem, options, answer, analysis):
    return {'id': id, 'stem': stem, 'options': list(options), 'answer': answer, 'analysis': analysis}


