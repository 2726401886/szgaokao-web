def selfcheck():
    print('\n--- selfcheck ---')
    for name, obj in (('history', KNOWLEDGE), ('history_exam', EXAM), ('history_link', LINK)):
        p = os.path.join(DATA_DIR, name + '.json')
        s = json.dumps(obj, ensure_ascii=False)
        assert len(s) > 2000, name + ' 内容过小，疑似生成失败'
        print('  %-14s %7d bytes  OK' % (name, len(s)))

    gs = [(g['id'], g['title'], len(g['items'])) for g in KNOWLEDGE['sections']['knowledge']['groups']]
    ni = sum(n for _, _, n in gs)
    print('  知识点：%d 组 / %d 条' % (len(gs), ni))
    assert len(gs) == 6 and ni >= 25, '知识点规模不足'

    qs = EXAM['questions']
    import collections
    tc = collections.Counter(q['type'] for q in qs)
    print('  题库：%d 题  %s' % (len(qs), dict(tc)))
    assert len(qs) >= 55, '题库数量不足'
    for q in qs:
        if q['type'] == 'choice':
            assert len(q['options']) == 4 and 0 <= q['answer'] < 4, q['id'] + ' 选项/答案异常'
            assert len(set(q['options'])) == 4, q['id'] + ' 选项重复'
            assert q['analysis'].strip(), q['id'] + ' 缺解析'
    # 答案分布
    ch = [q for q in qs if q['type'] == 'choice']
    dist = collections.Counter(q['answer'] for q in ch)
    print('  单选答案分布 A/B/C/D = %s' % [dist.get(i, 0) for i in range(4)])
    assert all(dist.get(i, 0) > 0 for i in range(4)), '答案分布不均'
    # id 唯一
    ids = [q['id'] for q in qs]
    assert len(ids) == len(set(ids)), '题库 id 重复'

    us = LINK['units']
    print('  专题包：%d 单元' % len(us))
    assert len(us) == 5, '专题单元数不符'
    for u in us:
        assert u['points'] and u['quiz'], u['id'] + ' 内容缺失'
        for p in u['points']:
            assert p.get('h') and p.get('body') and p.get('eg') and p.get('tip'), u['id'] + ' 要点字段缺失'
    print('selfcheck 全部通过')


