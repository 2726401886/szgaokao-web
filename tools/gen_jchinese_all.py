def balance_answers(questions):
    # 全局轮转：按题目顺序把正确项依次摆到 0/1/2/3，保证 ABCD 分布均匀
    idx = 0
    for q in questions:
        if q["type"] != "choice":
            continue
        desired = idx % 4
        idx += 1
        opts = q["options"]
        correct = opts[q["answer"]]
        n = len(opts)
        shift = (q["answer"] - desired) % n
        new_opts = opts[shift:] + opts[:shift]
        assert new_opts[desired] == correct, "balance failed"
        q["options"] = new_opts
        q["answer"] = desired
    return questions

