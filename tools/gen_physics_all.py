import io, os, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, 'data')
os.makedirs(DATA_DIR, exist_ok=True)


def dump(name, obj):
    p = os.path.join(DATA_DIR, name)
    io.open(p, 'w', encoding='utf-8').write(json.dumps(obj, ensure_ascii=False, indent=0))
    print('wrote', p, os.path.getsize(p), 'bytes')


_exam_seq = {'choice': 0, 'fill': 0, 'read': 0, 'write': 0}


def qc(grade, topic, difficulty, stem, options, answer, analysis):
    _exam_seq['choice'] += 1
    assert len(options) == 4, '选项必须为 4 个: ' + stem[:20]
    assert 0 <= answer < len(options), 'answer 越界'
    assert len(set(options)) == 4, '选项重复: ' + stem[:20]
    return {'id': 'phc%03d' % _exam_seq['choice'], 'grade': grade, 'topic': topic,
            'type': 'choice', 'difficulty': difficulty, 'stem': stem,
            'options': list(options), 'answer': answer, 'analysis': analysis}


def qf(grade, topic, difficulty, stem, answer, analysis):
    _exam_seq['fill'] += 1
    return {'id': 'phf%03d' % _exam_seq['fill'], 'grade': grade, 'topic': topic,
            'type': 'fill', 'difficulty': difficulty, 'stem': stem,
            'answer': answer, 'analysis': analysis}


def qr(grade, topic, difficulty, title, passage, subs):
    _exam_seq['read'] += 1
    assert subs and all(0 <= s['answer'] < len(s['options']) for s in subs), 'read 小题答案越界'
    # 导读层解析：read 题的解析由各小题的 analysis 承载，外层给一句导读说明
    return {'id': 'phr%03d' % _exam_seq['read'], 'grade': grade, 'topic': topic,
            'type': 'read', 'difficulty': difficulty, 'title': title,
            'passage': passage, 'questions': subs,
            'analysis': '阅读材料并逐题作答，答案见各小题解析。'}


def lq(grade, topic, difficulty, stem, answer, analysis):
    _exam_seq['write'] += 1
    return {'id': 'phw%03d' % _exam_seq['write'], 'grade': grade, 'topic': topic,
            'type': 'write', 'difficulty': difficulty, 'stem': stem,
            'answer': answer, 'analysis': analysis}


def kp(id, term, jieshi, kao):
    assert 0 <= kao['answer'] < len(kao['options']), 'kao 答案越界: ' + id
    return {'id': id, 'term': term, 'jieshi': jieshi, 'kao': kao}


def sub(stem, options, answer, analysis):
    return {'stem': stem, 'options': list(options), 'answer': answer, 'analysis': analysis}


def lp(id, points, quiz):
    assert all(0 <= q['answer'] < len(q['options']) for q in quiz), id + ' quiz 答案越界'
    return {'id': id, 'points': points, 'quiz': quiz}


def pt(h, body, eg, tip):
    return {'h': h, 'body': body, 'eg': eg, 'tip': tip}


def lq2(id, stem, options, answer, analysis):
    return {'id': id, 'stem': stem, 'options': list(options), 'answer': answer, 'analysis': analysis}


