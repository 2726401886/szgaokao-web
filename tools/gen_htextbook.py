def tb(t, author, genre, recite=False, note=""):
    """课文条目"""
    return {"title": t, "author": author, "genre": genre, "recite": recite, "note": note}

def kw(word, pinyin, jieshi):
    return {"word": word, "pinyin": pinyin, "jieshi": jieshi}

def rc(title, lines):
    return {"title": title, "lines": lines}

def px(stem, options, answer, analysis):
    return {"type": "choice", "stem": stem, "options": options, "answer": answer, "analysis": analysis}

def qf(stem, answer, analysis):
    return {"type": "fill", "stem": stem, "options": [], "answer": answer, "analysis": analysis}

